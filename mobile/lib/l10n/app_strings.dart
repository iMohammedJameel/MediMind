extension TrX on BuildContext {
  /// Current app language ('ar' | 'en'). Respects the active Localizations
  /// inherited widget; falls back to CacheHelper, then 'ar'.
  String get lang {
    try {
      final loc = Localizations.maybeLocaleOf(this)?.languageCode;
      if (loc != null && (loc == 'ar' || loc == 'en')) return loc;
      return CacheHelper.getLocale();
    } catch (_) {
      try {
        return CacheHelper.getLocale();
      } catch (_) {
        return 'ar';
      }
    }
  }

  /// Translate a catalog key.
  String tr(String key) => S.get(key, lang);

  /// Translate only if [maybeKey] is a known key; otherwise return it as-is
  /// (server-provided messages, raw literals).
  String trv(String maybeKey) {
    final lang_ = lang;
    final v = S._data[lang_]?[maybeKey];
    return v ?? maybeKey;
  }
}
